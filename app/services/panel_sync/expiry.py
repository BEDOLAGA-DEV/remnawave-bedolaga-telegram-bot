"""Дата окончания, которую бот отправляет в панель.

Отдельным модулем без тяжёлых зависимостей: правило нужно и сервису подписок, и
мониторингу, а кольцевые импорты между ними уже стоили отдельной починки.

Что умеет панель (проверено по её же контракту, одинаково в 3.0.0 и 3.4.3,
``libs/contract/commands/users/*.command.ts``):

* ``POST /api/users`` (создание) принимает ЛЮБУЮ дату, в том числе прошедшую;
* ``PATCH /api/users`` (обновление) прошедшую дату отклоняет —
  ``refine((date) => date > new Date())``, ошибка «Expiration date cannot be in
  the past». То же и у обоих массовых обновлений.

Отсюда и всё правило ниже: настоящую дату отправляем везде, где панель её
примет, а там, где не примет, выбираем между «оставить как есть» и «погасить
ближайшим допустимым моментом».
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

from app.utils.timezone import panel_datetime_to_utc


#: Ближайшее будущее, которым можно погасить дату у истёкшей подписки: прошедшую
#: панель при обновлении не примет, а «сейчас» сравнивает по СВОИМ часам. Бот и
#: панель нередко живут на разных серверах, и минуты вперёд не хватало: при
#: отставании часов бота панель отвечала «Expiration date cannot be in the past»,
#: статус уезжал первым запросом, а дата оставалась в будущем (проверено на
#: стенде с часами, сдвинутыми на три минуты). Пять минут покрывают обычный
#: разъезд. Истёкшей подписке статус в панель не уезжает (там нет «истекла»
#: руками, только «отключена админом»), поэтому эти минуты — окно, в которое
#: панель ещё считает аккаунт живым; по их истечении она гасит его сама, её
#: планировщик проверяет даты чаще раза в минуту (проверено на 3.4.3).
_MINIMUM_FUTURE = timedelta(minutes=5)

#: Если панель и это сочла прошлым — часы разъехались сильнее обычного: вторая
#: попытка с большим запасом и предупреждение в лог, чтобы оператор поправил NTP.
SKEW_RETRY_MARGIN = timedelta(minutes=15)

#: Насколько близкая к «сейчас» дата в панели считается уже погашенной.
#: Погашенная дата стоит на несколько минут вперёд и скоро становится прошлым,
#: но следующая синхронизация может прийти раньше — и, не будь этого окна, снова
#: двигала бы дату вперёд. Так и появлялось «истекла минуту назад» на каждый
#: прогон, ради избавления от которого всё и затевалось. Окно шире и повторной
#: попытки: её дата тоже наша, двигать её нечего.
_ALREADY_EXTINGUISHED = SKEW_RETRY_MARGIN + timedelta(minutes=4)


def panel_expire_at(
    end_date: datetime,
    *,
    is_active: bool,
    creating: bool,
    now: datetime | None = None,
    panel_current: datetime | None = None,
) -> datetime | None:
    """Что положить в ``expireAt`` панели. ``None`` — не отправлять поле вовсе.

    Пока дата окончания в будущем, в панель идёт она сама — и живой подписке, и
    заблокированной: доступ закрывает статус, а дата остаётся настоящей.

    Прошедшую дату панель принимает только при СОЗДАНИИ аккаунта — туда она и
    уходит, чтобы заведённая синхронизацией истёкшая подписка не появлялась в
    панели как «истекла минуту назад».

    При ОБНОВЛЕНИИ прошедшую дату панель отвергает, и здесь важно, что в панели
    стоит сейчас (``panel_current``, ``None`` — неизвестно):

    * там уже прошлое или неизвестно — поле не отправляется. Раньше туда уходило
      «сейчас плюс минута», и панель после каждой синхронизации показывала
      «истекла минуту назад»: настоящая дата окончания затиралась, история
      терялась, а оператор не мог понять, когда подписка на самом деле кончилась;
    * там будущее — панель считает подписку живой, хотя в боте она истекла (так
      бывает после ручной правки, импорта или переноса базы). Тогда отправляем
      ближайший допустимый момент: панель гаснет и дальше держит прошедшую дату,
      поэтому следующие синхронизации её уже не трогают.
    """
    moment = now or datetime.now(UTC)
    if is_active or panel_datetime_to_utc(end_date) > moment:
        return end_date
    if creating:
        return end_date
    return stale_panel_expire_at(panel_current, end_date=end_date, now=moment)


def stale_panel_expire_at(
    panel_current: datetime | None,
    *,
    end_date: datetime,
    now: datetime | None = None,
) -> datetime | None:
    """Чем погасить дату подписки в панели. ``None`` — не трогать.

    Отдельной функцией, потому что массовая синхронизация узнаёт дату панели уже
    из ответа на ``PATCH``: там сравнивать нечего заранее, а правило должно быть
    одно и то же.

    Гасим ТОЛЬКО у подписки, чья дата окончания уже прошла. Заблокированный
    пользователь с ещё не истёкшей подпиской тоже уходит в панель отключённым,
    но его настоящая дата окончания — в будущем, и подменять её «ближайшей
    минутой» значило бы терять срок, за который человек заплатил.
    """
    if panel_current is None:
        return None
    moment = now or datetime.now(UTC)
    if panel_datetime_to_utc(end_date) > moment:
        return None
    if panel_datetime_to_utc(panel_current) <= moment + _ALREADY_EXTINGUISHED:
        # Либо там уже прошлое, либо это наше собственное гашение — двигать
        # нечего: панель погасит аккаунт сама, как только дата пройдёт.
        return None
    return moment + _MINIMUM_FUTURE
