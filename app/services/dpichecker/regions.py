GROUPED_LOCATION = 'russia'


def group_pops(location: str, pops: list[dict[str, Any]]) -> dict[str, Any]:
    """Номера точек по округам и «Республикам»; точка с регионом вне карты остаётся только в общем списке."""
    if location != GROUPED_LOCATION:
        return {'districts': [], 'republics': []}
    districts = [
        {'code': code, 'name': name, 'pop_ids': [pop['id'] for pop in pops if pop.get('region') in set(regions)]}
        for code, name, regions in DISTRICTS
    ]
    republics = [pop['id'] for pop in pops if pop.get('region') in REPUBLICS]
    return {'districts': districts, 'republics': republics}
