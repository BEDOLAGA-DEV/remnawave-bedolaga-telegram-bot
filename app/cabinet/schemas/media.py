"""Общие правила для медиа Telegram в кабинете."""

# Telegram file_id — непрозрачная URL-safe base64-строка. Единственный источник
# правила: его же используют прокси скачивания (routes/media.py) и схемы, куда
# file_id приходит от фронта (рассылки). URL, пустая строка и прочее — не file_id,
# такое Telegram отвергнет на отправке у каждого получателя.
TELEGRAM_FILE_ID_PATTERN = r'^[A-Za-z0-9_-]{16,256}$'
